// Writes js/render/handfont-data.js from the vendored woff2, so the game can
// load its handwriting with no request at all (Playables: zero external calls,
// and every flavour of the build is one self-contained file).
//
//   node tools/lib/embed-font.mjs
//
// Source: @fontsource/patrick-hand 5.3.0 (npm), Patrick Hand by Patrick
// Wagesreiter, SIL Open Font License 1.1 — vendor/fonts/PatrickHand-OFL.txt.
import { readFileSync, writeFileSync } from 'node:fs';
const ROOT = new URL('../../', import.meta.url).pathname;
const b64 = readFileSync(ROOT + 'vendor/fonts/patrick-hand-latin-400-normal.woff2').toString('base64');
writeFileSync(ROOT + 'js/render/handfont-data.js',
  '// GENERATED by tools/lib/embed-font.mjs — do not edit. Patrick Hand (SIL OFL 1.1),\n' +
  '// latin subset, woff2, base64. Licence: vendor/fonts/PatrickHand-OFL.txt\n' +
  `export const HAND_WOFF2 = '${b64}';\n`);
console.log(`handfont-data.js: ${b64.length} chars`);
